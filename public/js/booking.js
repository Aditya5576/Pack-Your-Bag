// Generate the HTML layout for the seat selection grid
function renderSeatLayout(trip) {
  const container = document.getElementById("seat-grid-container");
  let html = "";

  if (trip.type === "bus") {
    // Bus seat configuration: 40 seats. 10 rows. 2-Aisle-2 structure.
    for (let row = 0; row < 10; row++) {
      html += `<div class="seat-row">`;
      for (let col = 0; col < 4; col++) {
        if (col === 2) {
          html += `<div class="aisle-spacer"></div>`; // Aisle
        }
        const seatIndex = row * 4 + col;
        const seatNo = `${row + 1}${["A", "B", "C", "D"][col]}`;
        const status = trip.seatLayout[seatIndex] === "booked" ? "booked" : "available";
        html += `
          <button class="seat-item bus-seat ${status}" data-index="${seatIndex}" data-no="${seatNo}" ${status === "booked" ? "disabled" : ""}>
            ${seatNo}
          </button>
        `;
      }
      html += `</div>`;
    }
  } else if (trip.type === "train") {
    // Train layout: Compartment style berths. 72 Berths.
    // 9 compartments, each containing 8 berths (Lower, Middle, Upper, Lower, Middle, Upper, Side Lower, Side Upper)
    for (let comp = 0; comp < 9; comp++) {
      html += `<div class="train-compartment">`;
      html += `<div class="compartment-label">Compartment ${comp + 1}</div>`;

      // Cabin berths (Left 3, Right 3)
      html += `<div class="cabin-berths">`;
      const berthLabels = ["L", "M", "U", "L", "M", "U"];
      for (let b = 0; b < 6; b++) {
        if (b === 3) {
          html += `<div class="aisle-spacer"></div>`; // Aisle spacer for column 4
        }
        const seatIndex = comp * 8 + b;
        const seatNo = `${comp * 8 + b + 1}-${berthLabels[b]}`;
        const status = trip.seatLayout[seatIndex] === "booked" ? "booked" : "available";
        html += `
          <button class="seat-item train-berth ${status}" data-index="${seatIndex}" data-no="${seatNo}" ${status === "booked" ? "disabled" : ""}>
            ${seatNo}
          </button>
        `;
      }
      html += `</div>`;

      // Side berths (Side Lower, Side Upper)
      html += `<div class="side-berths">`;
      const sideLabels = ["SL", "SU"];
      for (let sb = 0; sb < 2; sb++) {
        const seatIndex = comp * 8 + 6 + sb;
        const seatNo = `${comp * 8 + 6 + sb + 1}-${sideLabels[sb]}`;
        const status = trip.seatLayout[seatIndex] === "booked" ? "booked" : "available";
        html += `
          <button class="seat-item train-berth side ${status}" data-index="${seatIndex}" data-no="${seatNo}" ${status === "booked" ? "disabled" : ""}>
            ${seatNo}
          </button>
        `;
      }
      html += `</div>`;
      html += `</div>`;
    }
  } else if (trip.type === "flight") {
    // Flight seat layout: 30 rows. 3-Aisle-3 structure.
    for (let row = 0; row < 30; row++) {
      html += `<div class="seat-row flight-row">`;
      for (let col = 0; col < 6; col++) {
        if (col === 3) {
          html += `<div class="aisle-spacer"></div>`; // Aisle
        }
        const seatIndex = row * 6 + col;
        const seatNo = `${row + 1}${["A", "B", "C", "D", "E", "F"][col]}`;
        const status = trip.seatLayout[seatIndex] === "booked" ? "booked" : "available";
        html += `
          <button class="seat-item flight-seat ${status}" data-index="${seatIndex}" data-no="${seatNo}" ${status === "booked" ? "disabled" : ""}>
            ${seatNo}
          </button>
        `;
      }
      html += `</div>`;
    }
  }

  container.innerHTML = html;
}

// Bind clicks on seats
function bindSeatEvents(seatsRequired, trip) {
  const proceedBtn = document.getElementById("btn-proceed-details");
  const selectedSeatsBadge = document.getElementById("selected-seats-badge");
  const selectedPriceBadge = document.getElementById("selected-price-badge");

  const seatButtons = document.querySelectorAll(".seat-item.available");

  seatButtons.forEach((btn) => {
    btn.addEventListener("click", () => {
      const idx = parseInt(btn.getAttribute("data-index"));
      const seatNo = btn.getAttribute("data-no");

      const stateIndex = window.appState.selectedSeats.indexOf(seatNo);

      if (stateIndex > -1) {
        // Deselect seat
        window.appState.selectedSeats.splice(stateIndex, 1);
        btn.classList.remove("selected");
      } else {
        // Enforce maximum seat selection limit
        if (window.appState.selectedSeats.length >= seatsRequired) {
          // Deselect the oldest choice to replace it
          const firstSelected = window.appState.selectedSeats.shift();
          const oldBtn = document.querySelector(`.seat-item[data-no="${firstSelected}"]`);
          if (oldBtn) oldBtn.classList.remove("selected");
        }

        window.appState.selectedSeats.push(seatNo);
        btn.classList.add("selected");
      }

      // Update sidebar details
      const countSelected = window.appState.selectedSeats.length;
      if (countSelected > 0) {
        selectedSeatsBadge.textContent = window.appState.selectedSeats.join(", ");
        selectedPriceBadge.textContent = `₹${countSelected * trip.price}`;
      } else {
        selectedSeatsBadge.textContent = "None";
        selectedPriceBadge.textContent = `₹0`;
      }

      // Enable proceed button when exact required count is selected
      if (countSelected === seatsRequired) {
        proceedBtn.removeAttribute("disabled");
      } else {
        proceedBtn.setAttribute("disabled", "true");
      }
    });
  });

  proceedBtn.addEventListener("click", () => {
    // Generate initial passenger array with empty fields or loaded details
    const db = getDB();
    const saved = db.passengers || [];

    window.appState.passengersDetails = [];
    for (let i = 0; i < seatsRequired; i++) {
      // Auto-fill first passenger with logged-in user details if available
      if (i === 0 && window.appState.currentUser) {
        window.appState.passengersDetails.push({
          name: window.appState.currentUser.name,
          age: window.appState.currentUser.age || 24,
          gender: window.appState.currentUser.gender || "Male",
          seatNo: window.appState.selectedSeats[i]
        });
      } else if (saved[i]) {
        // Auto fill subsequent fields with saved profiles if they exist
        window.appState.passengersDetails.push({
          name: saved[i].name,
          age: saved[i].age,
          gender: saved[i].gender,
          seatNo: window.appState.selectedSeats[i]
        });
      } else {
        window.appState.passengersDetails.push({
          name: "",
          age: "",
          gender: "Male",
          seatNo: window.appState.selectedSeats[i]
        });
      }
    }

    navigateTo("#/checkout");
  });
}

