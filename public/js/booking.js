// Calculate the booking totals dynamically
function calculateFareBreakdown() {
  const selectedTrip = window.appState.selectedTrip;
  const selectedSeats = window.appState.selectedSeats;
  const coupon = window.appState.appliedCoupon;

  const baseFare = selectedSeats.length * selectedTrip.price;
  let discount = 0;

  if (coupon) {
    if (coupon.type === "percentage") {
      discount = (baseFare * coupon.value) / 100;
      if (coupon.maxDiscount && discount > coupon.maxDiscount) {
        discount = coupon.maxDiscount;
      }
    } else if (coupon.type === "flat") {
      discount = coupon.value;
    }
  }

  // Base minus discount cannot go below 0
  const taxableFare = Math.max(0, baseFare - discount);
  const gst = Math.floor(taxableFare * 0.18);
  const grandTotal = taxableFare + gst;

  // Sync to elements
  document.getElementById("summary-base-fare").textContent = `₹${baseFare}`;

  const couponRow = document.getElementById("coupon-row");
  if (coupon && discount > 0) {
    couponRow.style.display = "flex";
    document.getElementById("coupon-code-label").textContent = coupon.code;
    document.getElementById("summary-discount").textContent = `-₹${discount}`;
  } else {
    couponRow.style.display = "none";
  }

  document.getElementById("summary-gst").textContent = `₹${gst}`;
  document.getElementById("summary-grand-total").textContent = `₹${grandTotal}`;
  document.getElementById("payment-modal-amount").textContent = `₹${grandTotal}`;

  // Store values in appState for ticket billing extraction
  window.appState.bookingBill = {
    baseFare,
    discount,
    gst,
    grandTotal
  };
}

// Bind checkout handlers
function bindCheckoutEvents(savedPassengers) {
  const db = getDB();
  const savedList = document.getElementById("saved-profiles-list");

  // Load saved passenger profiles for quick clicking
  if (savedPassengers && savedPassengers.length > 0) {
    savedList.innerHTML = savedPassengers
      .map(
        (p) => `
      <button type="button" class="btn btn-outline btn-sm btn-quick-pax" data-name="${p.name}" data-age="${p.age}" data-gender="${p.gender}">
        ＋ ${p.name} (${p.age}, ${p.gender})
      </button>
    `
      )
      .join("");

    // Bind click
    document.querySelectorAll(".btn-quick-pax").forEach((btn) => {
      btn.addEventListener("click", (e) => {
        const target = e.currentTarget;
        const name = target.getAttribute("data-name");
        const age = target.getAttribute("data-age");
        const gender = target.getAttribute("data-gender");

        // Find first passenger form field that is empty, and fill it
        const nameInputs = document.querySelectorAll(".p-name");
        for (let input of nameInputs) {
          if (!input.value.trim()) {
            const idx = input.getAttribute("data-index");
            input.value = name;
            document.querySelectorAll(".p-age")[idx].value = age;
            document.querySelectorAll(".p-gender")[idx].value = gender;

            // Sync values to State
            window.appState.passengersDetails[idx].name = name;
            window.appState.passengersDetails[idx].age = parseInt(age);
            window.appState.passengersDetails[idx].gender = gender;

            showNotification(`Filled details for Passenger ${parseInt(idx) + 1}`, "info");
            break;
          }
        }
      });
    });
  } else {
    savedList.innerHTML =
      '<p class="text-muted">No saved passenger profiles. They will be saved on first checkout.</p>';
  }

  // Update passenger details on change
  document.querySelectorAll(".p-name").forEach((inp) => {
    inp.addEventListener("input", (e) => {
      const idx = e.target.getAttribute("data-index");
      window.appState.passengersDetails[idx].name = e.target.value;
    });
  });
  document.querySelectorAll(".p-age").forEach((inp) => {
    inp.addEventListener("input", (e) => {
      const idx = e.target.getAttribute("data-index");
      window.appState.passengersDetails[idx].age = parseInt(e.target.value) || "";
    });
  });
  document.querySelectorAll(".p-gender").forEach((sel) => {
    sel.addEventListener("change", (e) => {
      const idx = e.target.getAttribute("data-index");
      window.appState.passengersDetails[idx].gender = e.target.value;
    });
  });

  // Apply Coupon Action
  const applyBtn = document.getElementById("btn-apply-coupon");
  const couponInp = document.getElementById("coupon-input");
  const statusMsg = document.getElementById("coupon-message-status");

  applyBtn.addEventListener("click", () => {
    const code = couponInp.value.trim().toUpperCase();
    if (!code) {
      showNotification("Please enter a coupon code.", "error");
      return;
    }

    // Find coupon in DB
    const matchingCoupon = db.coupons.find((c) => c.code === code);
    if (!matchingCoupon) {
      statusMsg.className = "coupon-message error";
      statusMsg.textContent = "Invalid Coupon Code!";
      window.appState.appliedCoupon = null;
      calculateFareBreakdown();
      return;
    }

    // Validate min price / vehicle conditions
    const totalBase = window.appState.selectedSeats.length * window.appState.selectedTrip.price;
    if (matchingCoupon.minFare && totalBase < matchingCoupon.minFare) {
      statusMsg.className = "coupon-message error";
      statusMsg.textContent = `Min fare requirement of ₹${matchingCoupon.minFare} not met!`;
      window.appState.appliedCoupon = null;
      calculateFareBreakdown();
      return;
    }

    if (matchingCoupon.mode && matchingCoupon.mode !== window.appState.selectedTrip.type) {
      statusMsg.className = "coupon-message error";
      statusMsg.textContent = `Coupon valid only for ${matchingCoupon.mode} bookings!`;
      window.appState.appliedCoupon = null;
      calculateFareBreakdown();
      return;
    }

    // Apply coupon
    window.appState.appliedCoupon = matchingCoupon;
    statusMsg.className = "coupon-message success";
    statusMsg.textContent = `Coupon "${code}" applied successfully: ${matchingCoupon.description}`;
    showNotification("Coupon applied!", "success");
    calculateFareBreakdown();
  });

  // Open Payment modal
  const checkoutForm = document.getElementById("passenger-info-form");
  const paymentBtn = document.getElementById("btn-proceed-payment");
  const razorpayOverlay = document.getElementById("razorpay-overlay");

  paymentBtn.addEventListener("click", () => {
    // Validate forms
    if (!checkoutForm.reportValidity()) {
      showNotification("Please fill all passenger details correctly.", "error");
      return;
    }

    const email = document.getElementById("contact-email").value.trim();
    const mobile = document.getElementById("contact-mobile").value.trim();

    if (!email || !mobile || mobile.length !== 10) {
      showNotification("Please enter a valid email and 10-digit mobile number.", "error");
      return;
    }

    // Save contact details to state
    window.appState.deliveryEmail = email;
    window.appState.deliveryMobile = mobile;

    // Show Razorpay modal
    razorpayOverlay.style.display = "flex";
  });

  // Payment Tabs Toggle
  document.querySelectorAll(".pay-method-tab").forEach((tab) => {
    tab.addEventListener("click", (e) => {
      document.querySelectorAll(".pay-method-tab").forEach((t) => t.classList.remove("active"));
      e.currentTarget.classList.add("active");

      const method =
        e.currentTarget.getAttribute("data-mode") || e.currentTarget.textContent.toLowerCase().includes("card")
          ? "card"
          : e.currentTarget.textContent.toLowerCase().includes("upi")
            ? "upi"
            : "netbank";

      document.getElementById("view-card").style.display = method === "card" ? "block" : "none";
      document.getElementById("view-upi").style.display = method === "upi" ? "block" : "none";
      document.getElementById("view-netbank").style.display = method === "netbank" ? "block" : "none";
    });
  });

  // Cancel Payment
  document.getElementById("btn-cancel-payment").addEventListener("click", () => {
    razorpayOverlay.style.display = "none";
    showNotification("Payment cancelled by user.", "error");
  });

  // Complete Payment Action (simulating processing)
  document.getElementById("btn-submit-payment").addEventListener("click", () => {
    const loadingScreen = document.getElementById("payment-loading");
    const loadingStatus = document.getElementById("payment-loading-status");

    loadingScreen.style.display = "flex";

    // Simulate steps of payment processing
    setTimeout(() => {
      loadingStatus.textContent = "Authenticating transaction details...";

      setTimeout(() => {
        loadingStatus.textContent = "Securing booking confirmation...";

        setTimeout(() => {
          // Success Callback
          razorpayOverlay.style.display = "none";
          loadingScreen.style.display = "none";

          processSuccessfulBooking();
        }, 1200);
      }, 1000);
    }, 800);
  });
}

// Logic after payment resolves successfully
async function processSuccessfulBooking() {
  const state = window.appState;

  // Generate booking ID
  const bookingId = `PYB-${Math.floor(100000 + Math.random() * 900000)}`;

  const newBooking = {
    id: bookingId,
    tripId: state.selectedTrip.id,
    type: state.selectedTrip.type,
    provider: state.selectedTrip.provider,
    origin: state.selectedTrip.origin,
    destination: state.selectedTrip.destination,
    date: state.selectedTrip.date,
    departureTime: state.selectedTrip.departureTime,
    arrivalTime: state.selectedTrip.arrivalTime,
    duration: state.selectedTrip.duration,
    classSelected: state.selectedTrip.classSelected || "Standard",
    seats: [...state.selectedSeats],
    passengers: [...state.passengersDetails],
    billing: { ...state.bookingBill },
    email: state.deliveryEmail,
    mobile: state.deliveryMobile,
    bookingDate: new Date().toISOString(),
    status: "Confirmed"
  };

  // 1. Save booking to cloud database
  try {
    await window.dbAPI.addBooking(newBooking);
  } catch (err) {
    console.error("Booking save failed: ", err);
  }

  // 2. Update trip layout seats in database (mark selected seats as booked)
  const updatedLayout = [...state.selectedTrip.seatLayout];
  state.selectedSeats.forEach((seatNo) => {
    let seatIdx = -1;
    if (state.selectedTrip.type === "bus") {
      const row = parseInt(seatNo) - 1;
      const col = ["A", "B", "C", "D"].indexOf(seatNo.slice(-1));
      seatIdx = row * 4 + col;
    } else if (state.selectedTrip.type === "train") {
      seatIdx = parseInt(seatNo.split("-")[0]) - 1;
    } else if (state.selectedTrip.type === "flight") {
      const row = parseInt(seatNo) - 1;
      const col = ["A", "B", "C", "D", "E", "F"].indexOf(seatNo.slice(-1));
      seatIdx = row * 6 + col;
    }
    if (seatIdx > -1) {
      updatedLayout[seatIdx] = "booked";
    }
  });

  const seatsLeft = Math.max(0, state.selectedTrip.seatsAvailable - state.selectedSeats.length);
  try {
    await window.dbAPI.updateRouteSeats(state.selectedTrip.id, updatedLayout, seatsLeft);
  } catch (err) {
    console.error("Failed to update route seats: ", err);
  }

  // 3. Save new passenger profiles to database if they don't exist
  for (let p of state.passengersDetails) {
    const exists = state.currentUser.savedPassengers.some(
      (savedP) => savedP.name.toLowerCase() === p.name.toLowerCase()
    );
    if (!exists) {
      const newPax = {
        id: `P-${Math.floor(1000 + Math.random() * 9000)}`,
        name: p.name,
        age: p.age,
        gender: p.gender
      };
      try {
        await window.dbAPI.addPassenger(newPax);
        state.currentUser.savedPassengers.push(newPax);
      } catch (err) {
        console.error("Passenger save failed: ", err);
      }
    }
  }

  // Show message and route to ticket confirmation screen
  showNotification("Booking confirmed! Confetti is in the air!", "success");
  navigateTo(`#/ticket?bookingId=${bookingId}`);
}
